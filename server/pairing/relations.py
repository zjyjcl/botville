"""Cross-server relation transport (A-R3): the federation side only.

The gateways (B line) own relation business -- request ids as idempotency
keys, expiry, cooldowns, the state machine. This module only carries
their messages between two *paired* servers and checks the envelope
format. Flow:

  local gateway --POST /v1/pairing/internal/relations/<kind>-->
      pairing (service token)  builds + signs an envelope, sends it to
      the active peer only, with a timeout, no retries
  --POST <peer_api_url>/relations/<kind>--> peer fedgate
      (forwards only /_matrix/pairing/relations/{request,respond,revoke};
       X-Botville-Origin must be an active peer)
  --> peer pairing: per-peer HMAC (pairing-time shared_secret), +-300s
      timestamp window, nonce replay guard, rate limits, active gate,
      envelope format check
  --> RelationsGatewayClient.deliver() on the peer's gateway.

Kinds: `request` (friend request), `respond` (accept/reject: the decision
lives in the opaque payload), `revoke`.

Signature (same scheme as notify-severed, domain-separated so a signed
message can never be replayed against another endpoint or kind):

  hex HMAC-SHA256(shared_secret,
      "botville-relations-v1\\n<target>\\n<origin>\\n<ts>\\n<nonce>\\n"
      + sha256hex(body))      target = "relations/<kind>"

Envelope (the exact request body, canonical JSON; every key required,
no others):

  {"v": 1, "kind": "<kind>", "origin": "<sender server_name>",
   "destination": "<receiver server_name>",
   "request_id": "<16-64 of [0-9A-Za-z_-], generated by the sending gateway>",
   "payload": {...opaque JSON object for the gateways...}}

Everything fails closed: unknown/unsigned/stale/replayed/inactive senders,
a full replay guard, a malformed envelope and an absent or failing gateway
client are all refused -- nothing is ever delivered "best effort".

The HTTP client that will call the real gateway is deliberately NOT in
this build (A/B have not aligned the gateway's internal endpoints yet):
only the RelationsGatewayClient interface, the unconfigured default
(inbound answers 503 BV_RELATIONS_UNAVAILABLE) and a test recorder.
"""

import abc
import collections
import hashlib
import http.client
import hmac
import ipaddress
import json
import os
import re
import secrets
import socket
import threading
import time
import urllib.error
import urllib.request
from urllib.parse import urlsplit

RELATION_KINDS = ("request", "respond", "revoke")
ENVELOPE_VERSION = 1
ENVELOPE_KEYS = frozenset(
    ("v", "kind", "origin", "destination", "request_id", "payload"))
SIGNATURE_DOMAIN = "botville-relations-v1"
MAX_ENVELOPE_BYTES = 16384
MAX_PEER_RESPONSE_BYTES = 65536
REQUEST_ID_RE = re.compile(r"[0-9A-Za-z_-]{16,64}")
TS_WINDOW_SECONDS = 300.0
NONCE_RE = re.compile(r"[0-9a-f]{32,128}")
PEER_TIMEOUT_SECONDS = 10.0

# Gateway answers relayed to the sending server as-is; anything else
# (5xx, odd codes, non-object bodies, oversized bodies) is treated as
# "gateway unavailable" (503 BV_RELATIONS_UNAVAILABLE), so a broken
# gateway can never be mistaken for a business answer.
RELAYED_GATEWAY_STATUSES = frozenset(
    (200, 201, 202, 400, 403, 404, 409, 410, 422, 429))
MAX_GATEWAY_BODY_BYTES = 16384


class EnvelopeError(ValueError):
    """The relation envelope is malformed (reason is safe to return)."""


# --- signing ------------------------------------------------------------------

def relation_signature(shared_secret_hex, kind, origin, ts, nonce, body_bytes):
    body_hash = hashlib.sha256(body_bytes).hexdigest()
    message = "{}\nrelations/{}\n{}\n{}\n{}\n{}".format(
        SIGNATURE_DOMAIN, kind, origin, ts, nonce, body_hash)
    key = bytes.fromhex(shared_secret_hex)
    return hmac.new(key, message.encode("utf-8"), hashlib.sha256).hexdigest()


def build_relation_headers(shared_secret_hex, kind, origin, body_bytes,
                           now=None):
    ts = str(int(time.time() if now is None else now))
    nonce = secrets.token_hex(16)
    return {
        "X-Botville-Origin": origin,
        "X-Botville-Ts": ts,
        "X-Botville-Nonce": nonce,
        "X-Botville-Sig": relation_signature(
            shared_secret_hex, kind, origin, ts, nonce, body_bytes),
    }


def signature_ok(shared_secret_hex, kind, origin, ts, nonce, body, sig):
    """Constant-time check; shape-gated first (compare_digest needs ASCII)."""
    if not isinstance(sig, str) or not re.fullmatch(r"[0-9a-fA-F]{64}", sig):
        return False
    try:
        expected = relation_signature(shared_secret_hex, kind, origin, ts,
                                      nonce, body)
    except (ValueError, TypeError):  # corrupt stored secret: fail closed
        return False
    return hmac.compare_digest(sig.lower(), expected)


def timestamp_ok(ts, now=None):
    if not isinstance(ts, str) or not ts.isdigit() or not ts.isascii() \
            or len(ts) > 12:
        return False
    now = time.time() if now is None else now
    return abs(now - int(ts)) <= TS_WINDOW_SECONDS


def nonce_ok(nonce):
    return isinstance(nonce, str) and bool(NONCE_RE.fullmatch(nonce))


class StrictNonceGuard:
    """Replay guard that refuses instead of forgetting.

    Like service.NonceGuard (per-origin keys, remembered for twice the
    timestamp window) but when full it does NOT evict unexpired entries
    -- evicting would reopen the replay window for them -- and reports
    "full" so the caller fails closed (503) until entries age out.
    """

    SEEN, FRESH, FULL = "seen", "fresh", "full"

    def __init__(self, window=2 * TS_WINDOW_SECONDS, capacity=8192):
        self._window = window
        self._capacity = capacity
        self._seen = collections.OrderedDict()
        self._lock = threading.Lock()

    def check_and_mark(self, key, now=None):
        now = time.monotonic() if now is None else now
        with self._lock:
            while self._seen:
                oldest_at = next(iter(self._seen.values()))
                if now - oldest_at <= self._window:
                    break
                self._seen.popitem(last=False)
            if key in self._seen:
                return self.SEEN
            if len(self._seen) >= self._capacity:
                return self.FULL
            self._seen[key] = now
            return self.FRESH


# --- envelope -----------------------------------------------------------------

def encode_envelope(envelope):
    """Canonical bytes (sorted keys, no spaces) -- what gets signed/sent."""
    return json.dumps(envelope, sort_keys=True, separators=(",", ":"),
                      ensure_ascii=False).encode("utf-8")


def build_envelope(kind, origin, destination, request_id, payload):
    envelope = {"v": ENVELOPE_VERSION, "kind": kind, "origin": origin,
                "destination": destination, "request_id": request_id,
                "payload": payload}
    validate_envelope(envelope, kind, origin, destination)
    if len(encode_envelope(envelope)) > MAX_ENVELOPE_BYTES:
        raise EnvelopeError("envelope too large")
    return envelope


def validate_request_id(request_id):
    if not isinstance(request_id, str) or not REQUEST_ID_RE.fullmatch(request_id):
        raise EnvelopeError(
            "request_id must be 16-64 characters of [0-9A-Za-z_-]")


def validate_envelope(envelope, kind, origin, destination):
    """Format only -- the business meaning of payload is the gateway's.

    `origin` is the authenticated sender, `destination` our own name;
    the envelope must agree with both (a message signed for one server
    cannot be delivered to another)."""
    if not isinstance(envelope, dict):
        raise EnvelopeError("envelope must be a JSON object")
    keys = set(envelope)
    if keys != ENVELOPE_KEYS:
        raise EnvelopeError("envelope keys must be exactly {}".format(
            ", ".join(sorted(ENVELOPE_KEYS))))
    version = envelope["v"]
    if type(version) is not int or version != ENVELOPE_VERSION:
        raise EnvelopeError("unsupported envelope version")
    if envelope["kind"] != kind:
        raise EnvelopeError("envelope kind does not match the endpoint")
    if envelope["origin"] != origin:
        raise EnvelopeError("envelope origin does not match the sender")
    if envelope["destination"] != destination:
        raise EnvelopeError("envelope is not addressed to this server")
    validate_request_id(envelope["request_id"])
    if not isinstance(envelope["payload"], dict):
        raise EnvelopeError("payload must be a JSON object")


def parse_envelope_bytes(raw, kind, origin, destination):
    if len(raw) > MAX_ENVELOPE_BYTES:
        raise EnvelopeError("envelope too large")
    try:
        envelope = json.loads(raw.decode("utf-8"))
    except (ValueError, UnicodeDecodeError):
        raise EnvelopeError("envelope is not valid JSON") from None
    validate_envelope(envelope, kind, origin, destination)
    return envelope


# --- gateway client interface ------------------------------------------------

class GatewayUnavailable(Exception):
    """The local gateway cannot take relation messages right now.

    The first argument should be a short reason CODE ([a-z_], e.g.
    "not_configured", "timeout"); pairing logs only that code, never free
    text, because a client could put request/response bodies into it
    (#249 review 4)."""


SAFE_REASON_RE = re.compile(r"[a-z][a-z0-9_]{0,39}")


def safe_reason(exc):
    """Loggable reason for a GatewayUnavailable: its code if it is a short
    [a-z0-9_] token, else the generic "unavailable"."""
    code = exc.args[0] if getattr(exc, "args", None) else None
    if isinstance(code, str) and SAFE_REASON_RE.fullmatch(code):
        return code
    return "unavailable"


class GatewayResult:
    def __init__(self, status, body):
        self.status = status
        self.body = body


class RelationsGatewayClient(abc.ABC):
    """How pairing hands a verified inbound relation message to the local
    gateway. Implementations must raise GatewayUnavailable (never return
    a guess) when the gateway cannot be reached or answers garbage; the
    inbound handler turns that into 503."""

    @abc.abstractmethod
    def deliver(self, kind, envelope, meta):
        """`meta` = {"origin", "sent_at", "received_at"} (transport facts
        already verified). Returns a GatewayResult."""


class UnconfiguredRelationsGateway(RelationsGatewayClient):
    """Default: no gateway configured -> every inbound message is refused
    with an explicit 'unavailable' (fail-closed)."""

    def deliver(self, kind, envelope, meta):
        raise GatewayUnavailable("not_configured")


class RecordingRelationsGateway(RelationsGatewayClient):
    """TEST ONLY (unit tests and the federation e2e stack): appends one
    JSON line {kind, envelope, meta} per delivery to `path` and answers
    202 {"accepted": true, "request_id": ...}. Never use in production --
    it accepts everything."""

    def __init__(self, path):
        self.path = path
        self._lock = threading.Lock()

    def deliver(self, kind, envelope, meta):
        line = json.dumps({"kind": kind, "envelope": envelope, "meta": meta},
                          sort_keys=True) + "\n"
        try:
            with self._lock, open(self.path, "a", encoding="utf-8") as handle:
                handle.write(line)
        except OSError:
            raise GatewayUnavailable("recorder_write_failed") from None
        return GatewayResult(202, {"accepted": True,
                                   "request_id": envelope["request_id"]})


def checked_gateway_result(result):
    """(status, body) safe to relay, or raise GatewayUnavailable."""
    if not isinstance(result, GatewayResult) or \
            type(result.status) is not int or \
            result.status not in RELAYED_GATEWAY_STATUSES or \
            not isinstance(result.body, dict):
        raise GatewayUnavailable("unusable_result")
    try:
        size = len(json.dumps(result.body).encode("utf-8"))
    except (TypeError, ValueError):
        raise GatewayUnavailable("body_not_json") from None
    if size > MAX_GATEWAY_BODY_BYTES:
        raise GatewayUnavailable("body_too_large")
    return result.status, result.body


def validate_gateway_http(url, token):
    """Local, trusted hop; deliberately not the peer target policy.

    Reject ambiguous bases and header injection without echoing values.
    http is valid on container/loopback networks; https uses default TLS.
    """
    try:
        parts = urlsplit(url or "")
        valid = (parts.scheme in ("http", "https") and parts.hostname
                 and not parts.username and not parts.password
                 and parts.path in ("", "/") and not parts.query
                 and not parts.fragment and not any(c.isspace() for c in url))
        parts.port
    except (ValueError, TypeError):
        valid = False
    if not valid:
        raise ValueError("PAIRING_RELATIONS_GATEWAY_URL requires an http(s) origin")
    if not token or len(token) < 32 or any(ord(c) < 33 or ord(c) > 126 for c in token):
        raise ValueError("GATEWAY_RELATIONS_INBOUND_TOKEN requires at least 32 printable ASCII characters")


class HttpRelationsGateway(RelationsGatewayClient):
    """#257 local inbound contract. Bounded I/O, no retries or redirects.

    Never retain remote text in exceptions (including exception context).
    Proxy environment settings are bypassed for this local trusted hop.
    """
    def __init__(self, url, token, timeout=10):
        validate_gateway_http(url, token)
        self.url = url.rstrip("/")
        self._token = token
        self.timeout = timeout

    def deliver(self, kind, envelope, meta):
        if kind not in RELATION_KINDS:
            raise GatewayUnavailable("unsupported_kind")
        try:
            raw = json.dumps({"kind": kind, "envelope": envelope, "meta": meta},
                             ensure_ascii=False, sort_keys=True,
                             separators=(",", ":"), allow_nan=False).encode("utf-8")
            if len(raw) > MAX_GATEWAY_BODY_BYTES:
                raise GatewayUnavailable("request_too_large")
            class NoRedirect(urllib.request.HTTPRedirectHandler):
                def redirect_request(self, *args, **kwargs):
                    return None
            opener = urllib.request.build_opener(
                urllib.request.ProxyHandler({}), NoRedirect())
            request = urllib.request.Request(
                self.url + "/_internal/relations/" + kind, data=raw,
                headers={"Authorization": "Bearer " + self._token,
                         "Content-Type": "application/json"}, method="POST")
            try:
                response = opener.open(request, timeout=self.timeout)
            except urllib.error.HTTPError as exc:
                response = exc
            with response:
                if response.status not in RELAYED_GATEWAY_STATUSES:
                    raise GatewayUnavailable("unusable_result")
                body = response.read(MAX_GATEWAY_BODY_BYTES + 1)
                if len(body) > MAX_GATEWAY_BODY_BYTES:
                    raise GatewayUnavailable("body_too_large")
                result = GatewayResult(response.status, json.loads(body.decode("utf-8")))
                checked_gateway_result(result)
                return result
        except GatewayUnavailable:
            raise
        except Exception:
            raise GatewayUnavailable("http_unavailable") from None


GATEWAY_MODES = ("none", "test-recorder", "http")


def build_gateway_client(mode, record_path=None, url=None, token=None):
    if mode == "http":
        return HttpRelationsGateway(url, token)
    if mode == "none":
        return UnconfiguredRelationsGateway()
    if mode == "test-recorder":
        return RecordingRelationsGateway(record_path)
    raise ValueError(mode)


# --- outbound -----------------------------------------------------------------

class PeerTimeout(Exception):
    """The peer did not answer within PEER_TIMEOUT_SECONDS."""


def post_relation(url, body, headers, ssl_context=None,
                  timeout=PEER_TIMEOUT_SECONDS):
    """POST a signed envelope to the peer. Returns (status, body-or-None);
    raises PeerTimeout / OSError. No redirects are followed (a 3xx is
    returned as the status), no retries -- the gateway retries with the
    same request_id if it wants to."""

    class _NoRedirect(urllib.request.HTTPRedirectHandler):
        def redirect_request(self, *args, **kwargs):
            return None

    handlers = [_NoRedirect()]
    if ssl_context is not None:
        handlers.append(urllib.request.HTTPSHandler(context=ssl_context))
    opener = urllib.request.build_opener(*handlers)
    hdrs = {"Content-Type": "application/json", "Accept": "application/json"}
    hdrs.update(headers)
    req = urllib.request.Request(url, data=body, headers=hdrs, method="POST")
    try:
        with opener.open(req, timeout=timeout) as resp:
            status, raw = resp.status, resp.read(MAX_PEER_RESPONSE_BYTES + 1)
    except urllib.error.HTTPError as exc:
        status, raw = exc.code, exc.read(MAX_PEER_RESPONSE_BYTES + 1)
    except (TimeoutError, socket.timeout) as exc:  # distinct before 3.10
        raise PeerTimeout(str(exc)) from None
    except urllib.error.URLError as exc:
        if isinstance(exc.reason, (TimeoutError, socket.timeout)):
            raise PeerTimeout(str(exc.reason)) from None
        raise OSError(str(exc.reason)) from None
    except (http.client.HTTPException, ValueError) as exc:
        # Garbage status line / bad URL: transport failure, never a crash.
        raise OSError("{}: {}".format(type(exc).__name__, exc)) from None
    if len(raw) > MAX_PEER_RESPONSE_BYTES:
        return status, None
    try:
        parsed = json.loads(raw.decode("utf-8")) if raw else None
    except (ValueError, UnicodeDecodeError):
        parsed = None
    return status, parsed if isinstance(parsed, dict) else None


# --- outbound target policy (A-R4, #249 review 2) ------------------------------

TARGET_OK, TARGET_AUDIT, TARGET_REFUSED = "ok", "audit", "refused"


# RFC 6598 shared address space. ipaddress.IPv4Address.is_private is
# False for this range on Python 3.9–3.12 (the pairing image is 3.12),
# so a hand-rolled private/loopback/reserved check would treat it as
# public and allow it with no AUDIT.
_SHARED_ADDRESS_SPACE = ipaddress.ip_network("100.64.0.0/10")


def _non_public(address):
    ip = ipaddress.ip_address(address)
    if getattr(ip, "ipv4_mapped", None):
        ip = ip.ipv4_mapped
    return (ip.is_private or ip.is_loopback or ip.is_link_local or
            ip.is_reserved or ip.is_multicast or ip.is_unspecified or
            (ip.version == 4 and ip in _SHARED_ADDRESS_SPACE))


def target_policy(url, allow_private, resolve=socket.getaddrinfo):
    """Where may an outbound relation go? Returns (verdict, detail).

    Production rule: https only, and every address the host resolves to
    must be public. With allow_private (PAIRING_RELATIONS_ALLOW_PRIVATE,
    test stacks with compose-network addresses) plain http and
    private/loopback/link-local addresses are allowed but reported as
    TARGET_AUDIT so the caller logs every such send. Unresolvable hosts are
    refused (fail closed). `detail` never contains credentials or the path.
    Residual risk: urllib resolves the name again when connecting (DNS
    rebinding between the two lookups); peer_api_url itself only comes
    from an authenticated pairing (redeem/accept)."""
    try:
        parts = urlsplit(url)
        host, port = parts.hostname, parts.port
    except ValueError:
        return TARGET_REFUSED, "unparsable url"
    scheme = (parts.scheme or "").lower()
    if scheme not in ("https", "http") or not host:
        return TARGET_REFUSED, "scheme {!r} not allowed".format(scheme)
    reasons = []
    if scheme == "http":
        reasons.append("plain http")
    try:
        infos = resolve(host, port or (443 if scheme == "https" else 80),
                        proto=socket.IPPROTO_TCP)
        addresses = sorted({info[4][0] for info in infos})
    except (OSError, UnicodeError, ValueError):
        return TARGET_REFUSED, "host {} does not resolve".format(host)
    if not addresses:
        return TARGET_REFUSED, "host {} does not resolve".format(host)
    try:
        private = [a for a in addresses if _non_public(a.split("%")[0])]
    except ValueError:
        return TARGET_REFUSED, "host {} resolves to a bad address".format(host)
    if private:
        reasons.append("non-public address {} for {}".format(
            ",".join(private), host))
    if not reasons:
        return TARGET_OK, host
    detail = "; ".join(reasons)
    return (TARGET_AUDIT if allow_private else TARGET_REFUSED), detail


def validate_outbound_request(obj):
    """Body of POST /v1/pairing/internal/relations/<kind> from the local
    gateway: exactly {destination, request_id, payload}."""
    if not isinstance(obj, dict) or set(obj) != {"destination", "request_id",
                                                 "payload"}:
        raise EnvelopeError(
            "body must be exactly {destination, request_id, payload}")
    if not isinstance(obj["destination"], str):
        raise EnvelopeError("destination must be a server name")
    validate_request_id(obj["request_id"])
    if not isinstance(obj["payload"], dict):
        raise EnvelopeError("payload must be a JSON object")


def record_path_ok(path):
    return bool(path) and os.path.isabs(path)
